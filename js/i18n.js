let currentLocale = readLocale();

function readLocale() {
  try {
    const saved = localStorage.getItem(LANGUAGE_KEY);
    if (LANGUAGES.some(({ code }) => code === saved)) return saved;
  } catch { /* storage may be unavailable */ }
  return 'en';
}

function interpolate(value, variables = {}) {
  return String(value).replace(/\{(\w+)\}/g, (_, key) => String(variables[key] ?? `{${key}}`));
}

export function getLocale() {
  return currentLocale;
}

export function getLanguage() {
  return LANGUAGES.find(({ code }) => code === currentLocale) || LANGUAGES[0];
}

export function t(key, variables = {}) {
  const value = messages[currentLocale]?.[key] ?? messages.en[key] ?? key;
  return interpolate(value, variables);
}

export function tp(key, count, variables = {}) {
  const suffix = count === 1 ? 'one' : 'other';
  return t(`${key}.${suffix}`, { ...variables, count });
}

export function setLocale(locale) {
  if (!LANGUAGES.some(({ code }) => code === locale)) return false;
  currentLocale = locale;
  try { localStorage.setItem(LANGUAGE_KEY, locale); } catch { /* no-op */ }
  applyTranslations();
  window.dispatchEvent(new CustomEvent('maybe:language-change', { detail: { locale } }));
  return true;
}

export function applyTranslations(root = document) {
  document.documentElement.lang = currentLocale === 'zh' ? 'zh-CN' : currentLocale;
  document.title = t('meta.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.description'));
  root.querySelectorAll?.('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll?.('[data-i18n-placeholder]').forEach((element) => {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
  });
  root.querySelectorAll?.('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
  });
}
